const std::string IndexOf::LINE_TEMPLATE =
	"<tr>"
	"<td class=\"icon\">{{ICON}}</td>"
	"<td><a href=\"{{LINK}}\">{{NAME}}</a></td>"
	"<td class=\"size\">{{SIZE_HUMAN}}</td>"
	"<td class=\"date\">{{CREATED_HUMAN}}</td>"
	"<td class=\"date\">{{DATE_HUMAN}}</td>"
	"</tr>\n";

const std::string IndexOf::FOOT_TEMPLATE =
	"</table>\n"
	"<div class=\"footer\">{{FILE_COUNT}} items &middot; Generated by {{SERVER_NAME}}</div>\n"
	"</body>\n"
	"</html>\n";

IndexOf::IndexOf(const std::string &root, const std::string &path)
{
	m_path = path;
	scanDirectory(root).generate();
}

IndexOf::~IndexOf()
{
}


IndexOf &IndexOf::scanDirectory(const std::string &root)
{
	std::string path = root + m_path;
	DIR		   *dir	 = opendir(path.c_str());
	if (!dir)
		throw std::runtime_error("Failed to open directory: " + path);

	struct dirent *entry;
	std::string	   fullPath;
	std::string	   entryName;

	while ((entry = readdir(dir)) != NULL)
	{
		entryName = entry->d_name;
		if (entryName == "." || entryName == "..")
			continue;
		m_files.push_back(File(entryName, m_path + "/" + entryName, root));
	}
	closedir(dir);


	return *this;
}

/**
 *
 * @brief Generates a single line of the index page.
 *
 * @param icon The icon to be displayed.
 * @param link The link to the file or directory.
 * @param name The name of the file or directory.
 * @param sizeHuman The human-readable size of the file.
 * @param dateHuman The human-readable last modified date of the file.
 *
 * @note This function uses the LINE_TEMPLATE constant to format the line.
 * @see LINE_TEMPLATE
 *
 * @return std::string The generated line.
 */
std::string IndexOf::generateLine(
	const std::string &icon,
	const std::string &link,
	const std::string &name,
	const std::string &sizeHuman,
	const std::string &createdHuman,
	const std::string &dateHuman)
{
	std::string line = LINE_TEMPLATE;

	String::replaceAll(line, "{{ICON}}", icon);
	String::replaceAll(line, "{{LINK}}", link);
	String::replaceAll(line, "{{NAME}}", name);
	String::replaceAll(line, "{{CREATED_HUMAN}}", createdHuman);
	String::replaceAll(line, "{{SIZE_HUMAN}}", sizeHuman);
	String::replaceAll(line, "{{DATE_HUMAN}}", dateHuman);
	return line;
}

/**
 *
 * @brief Generates the complete index page.
 *
 * @note This function uses the HEAD_TEMPLATE and FOOT_TEMPLATE constants to format the page.
 * @see HEAD_TEMPLATE
 * @see FOOT_TEMPLATE
 *
 * @note It also calls generateLine() for each file in the directory to create the individual lines.
 * @see generateLine()
 *
 * @return IndexOf& A reference to the current IndexOf object
 * for method chaining.
 *
 */
IndexOf &IndexOf::generate()
{
	std::string line;
	std::string result = HEAD_TEMPLATE;
	String::replaceAll(result, "{{PATH}}", String::htmlEscape(m_path));

	if (m_path != "/")
		result += generateLine("📁", "../", "..", "-", "-", "-");
	for (Vec<File>::const_iterator it = m_files.begin(); it != m_files.end(); ++it)
	{
		result += generateLine(
			it->getIcon(),
			it->getPath(),
			it->getName(),
			it->getSizeHuman(),
			it->getCreatedAtHuman(),
			it->getLastModifiedHuman());
	}
	std::string foot = FOOT_TEMPLATE;
	String::replaceAll(foot, "{{FILE_COUNT}}", Number::toString(m_files.size()));
	String::replaceAll(foot, "{{SERVER_NAME}}", SERVER_NAME);
	result += foot;
	m_page = result;


	return *this;
}



std::string IndexOf::getPage() const
{
	return m_page;
}

const Vec<File> &IndexOf::getFiles() const
{
	return m_files;
}